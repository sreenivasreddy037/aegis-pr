// AegisPR browser interface. Vanilla JS, no build step.
// All report text comes from analysed code, so it is inserted with textContent only.
"use strict";

const $ = (sel) => document.querySelector(sel);
const SVG_NS = "http://www.w3.org/2000/svg";
const VERDICT_TEXT = { request_changes: "Changes requested", comment: "Comments", approve: "Approved" };
const KIND_TEXT = { diff: "diff", caller: "caller", sandbox: "sandbox", policy: "policy", static: "analysis", llm: "model" };
const AGENT_NODES = ["security_auditor", "contract_reviewer", "regression_tester"];

let lastReport = null;
// Static mode: the page is hosted without the API (e.g. GitHub Pages). It then shows the
// precomputed review of the sample PR from static/demo/, generated by the same code at deploy time.
let staticDemo = null;

function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === "class") node.className = v;
    else if (k === "text") node.textContent = v;
    else if (v !== undefined && v !== null) node.setAttribute(k, v);
  }
  for (const c of children) if (c != null) node.append(c);
  return node;
}

function svg(tag, attrs = {}) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  return node;
}

// Render `backtick` spans as <code>, everything else as plain text nodes; no HTML parsing.
function richText(tag, text, attrs = {}) {
  const node = el(tag, attrs);
  String(text).split(/(`[^`]+`)/g).forEach((part) => {
    if (part.startsWith("`") && part.endsWith("`") && part.length > 2) node.append(el("code", { text: part.slice(1, -1) }));
    else if (part) node.append(document.createTextNode(part));
  });
  return node;
}

const short = (fq) => fq.split(".").slice(-1)[0];

// Paths are relative so the UI also works under a sub-path (https://user.github.io/aegis-pr/).
async function api(path, options = {}) {
  const res = await fetch(path, { headers: { "Content-Type": "application/json" }, ...options });
  if (!res.ok) {
    let detail = `${res.status} ${res.statusText}`;
    try {
      const body = await res.json();
      if (body.detail) detail = typeof body.detail === "string" ? body.detail : JSON.stringify(body.detail);
    } catch { /* not JSON */ }
    throw new Error(detail);
  }
  return res.json();
}

// ---------------------------------------------------------------- input pane

function describeDiff(text) {
  const files = (text.match(/^\+\+\+ /gm) || []).length;
  const added = (text.match(/^\+(?!\+\+)/gm) || []).length;
  const removed = (text.match(/^-(?!--)/gm) || []).length;
  if (!text.trim()) return "No diff yet.";
  return `${files} file${files === 1 ? "" : "s"}, +${added} −${removed} lines`;
}

function setDiff(text) {
  $("#diff").value = text;
  $("#diff-meta").textContent = describeDiff(text);
}

async function loadSample() {
  const sample = staticDemo ? staticDemo.sample : await api("sample");
  const repoSelect = $("#repo");
  if ([...repoSelect.options].some((o) => o.value === sample.repo_path)) repoSelect.value = sample.repo_path;
  setDiff(sample.diff);
}

function showError(message) {
  const box = $("#form-error");
  box.textContent = message;
  box.hidden = !message;
}

async function runReview(event) {
  if (event) event.preventDefault();
  const diff = $("#diff").value;
  if (!diff.trim()) {
    showError("Paste a unified diff or load the sample PR first.");
    return;
  }
  showError("");
  const button = $("#run");
  button.disabled = true;
  button.setAttribute("aria-busy", "true");
  button.querySelector(".run-label").textContent = "Reviewing…";
  try {
    if (staticDemo) {
      if (diff.trim() !== staticDemo.sample.diff.trim()) {
        throw new Error("this hosted preview can only show the sample PR. Run AegisPR locally to review your own diff.");
      }
      await new Promise((r) => setTimeout(r, 350));
      renderReport(staticDemo.report);
      return;
    }
    const report = await api("review/diff", {
      method: "POST",
      body: JSON.stringify({ diff, repo_path: $("#repo").value || null }),
    });
    renderReport(report);
  } catch (err) {
    showError(`Review failed: ${err.message}`);
  } finally {
    button.disabled = false;
    button.removeAttribute("aria-busy");
    button.querySelector(".run-label").textContent = "Run review";
  }
}

// ---------------------------------------------------------------- report

function renderReport(report) {
  lastReport = report;
  $("#empty").hidden = true;
  const root = $("#report");
  root.hidden = false;
  root.classList.remove("reveal");
  void root.offsetWidth; // restart the reveal animation
  root.classList.add("reveal");

  renderVerdict(report);
  renderGraph(report);
  renderFindings(report.findings);
  renderDropped(report.dropped);
  renderTimings(report);
}

function renderVerdict(report) {
  const box = $("#verdict");
  box.dataset.verdict = report.verdict;
  $("#verdict-label").textContent = VERDICT_TEXT[report.verdict] || report.verdict;
  const files = report.impact.files.length;
  $("#verdict-meta").textContent =
    `${report.mode === "live" ? "Live model" : "Offline mode"}, ${files} file${files === 1 ? "" : "s"}, ` +
    `${Math.round(report.total_latency_ms)} ms`;
  $("#verdict-summary").textContent = report.summary;

  const verified = report.findings.filter((f) => f.verified).length;
  const tallies = [
    [report.findings.length, "findings"],
    [verified, "proven by AST or sandbox"],
    [report.dropped.length, "filtered by the critic"],
    [report.impact.upstream.length, "callers within 2 hops"],
  ];
  const dl = $("#tallies");
  dl.replaceChildren(...tallies.map(([n, label]) => el("div", {}, el("dt", { text: label }), el("dd", { text: String(n) }))));
}

function renderGraph(report) {
  const g = $("#graph");
  g.replaceChildren();
  const impact = report.impact;
  const flagged = new Set(report.findings.map((f) => f.symbol).filter(Boolean));
  const brokenCallers = new Set(
    report.findings.filter((f) => f.category === "breaking_change").map((f) => f.symbol)
  );

  const columns = [[], [], []];
  for (const m of impact.modified_symbols) columns[0].push({ ...m, hop: 0 });
  for (const u of impact.upstream) if (u.hop >= 1 && u.hop <= 2) columns[u.hop].push(u);
  const maxHop = columns[2].length ? 2 : columns[1].length ? 1 : 0;

  const COL_W = 236, GAP = 96, NODE_H = 46, ROW_GAP = 14, PAD_X = 24, PAD_TOP = 44, PAD_BOTTOM = 20;
  const rows = Math.max(...columns.slice(0, maxHop + 1).map((c) => c.length), 1);
  const width = PAD_X * 2 + (maxHop + 1) * COL_W + maxHop * GAP;
  const height = PAD_TOP + rows * NODE_H + (rows - 1) * ROW_GAP + PAD_BOTTOM;
  g.setAttribute("viewBox", `0 0 ${width} ${height}`);
  g.setAttribute("width", width);
  g.setAttribute("height", height);

  const labels = ["Changed in this PR", "Direct callers (hop 1)", "Their callers (hop 2)"];
  const pos = new Map();
  columns.slice(0, maxHop + 1).forEach((col, ci) => {
    const x = PAD_X + ci * (COL_W + GAP);
    const label = svg("text", { x, y: 24, class: "col-label" });
    label.textContent = labels[ci];
    g.append(label);
    col.forEach((n, ri) => pos.set(n.symbol, { x, y: PAD_TOP + ri * (NODE_H + ROW_GAP), node: n }));
  });

  // Edges first so nodes sit on top. A caller points back to the symbol it depends on (`via`).
  for (const { x, y, node } of pos.values()) {
    if (!node.via || !pos.has(node.via)) continue;
    const target = pos.get(node.via);
    const x1 = target.x + COL_W, y1 = target.y + NODE_H / 2;
    const x2 = x, y2 = y + NODE_H / 2;
    const mid = (x1 + x2) / 2;
    const cls = ["edge", node.edge_kind || "calls"];
    if (brokenCallers.has(node.symbol)) cls.push("broken");
    g.append(svg("path", { d: `M${x1},${y1} C${mid},${y1} ${mid},${y2} ${x2},${y2}`, class: cls.join(" ") }));
  }

  for (const { x, y, node } of pos.values()) {
    const isFlagged = flagged.has(node.symbol);
    const cls = ["node", node.hop === 0 ? "modified" : "caller"];
    if (isFlagged) cls.push("flagged");
    const group = svg("g", { class: cls.join(" "), transform: `translate(${x},${y})` });
    const title = svg("title");
    title.textContent = `${node.symbol} — ${node.file_path}:${node.start_line}` +
      (node.via ? ` (${node.edge_kind} ${node.via})` : "");
    group.append(title, svg("rect", { width: COL_W, height: NODE_H }));
    const name = svg("text", { x: 12, y: 19, class: "name" });
    name.textContent = short(node.symbol) + (node.kind === "class" ? "" : "()");
    const where = svg("text", { x: 12, y: 36, class: "where" });
    const line = node.hop === 0 ? node.start_line : (node.call_lines[0] || node.start_line);
    where.textContent = `${node.file_path}:${line}`;
    group.append(name, where);
    const badgeText = brokenCallers.has(node.symbol) ? "breaks" : isFlagged ? "finding" : node.hop === 0 ? "changed" : "";
    if (badgeText) {
      const badge = svg("text", { x: COL_W - 12, y: 19, "text-anchor": "end", class: "badge" });
      badge.textContent = badgeText;
      group.append(badge);
    }
    g.append(group);
  }
}

function renderFindings(findings) {
  const list = $("#findings");
  if (!findings.length) {
    list.replaceChildren(el("li", { class: "no-findings", text: "No verified issues in this PR." }));
    return;
  }
  list.replaceChildren(...findings.map((f, i) => {
    const agents = [f.agent, ...f.corroborated_by].map((a) => a.replace(/_/g, " ")).join(" + ");
    const summary = el("summary", {},
      el("span", { class: "sev", text: f.severity }),
      richText("span", f.title, { class: "f-title" }),
      el("span", { class: f.verified ? "proof verified" : "proof", text: f.verified ? "Proven" : `${Math.round(f.confidence * 100)}% confidence` }),
      el("span", { class: "f-meta" },
        el("span", { class: "loc", text: `${f.file_path}:${f.line}` }),
        el("span", { text: f.category.replace(/_/g, " ") }),
        f.cwe ? el("span", { text: f.cwe }) : null,
        el("span", { text: agents }),
      ),
    );
    const evidence = el("ul", { class: "evidence" }, ...f.evidence.map((e) =>
      el("li", {}, el("span", { class: "kind", text: KIND_TEXT[e.kind] || e.kind }), el("span", { class: "detail", text: e.detail }))
    ));
    const body = el("div", { class: "f-body" },
      richText("p", f.description),
      el("h4", { text: "Evidence" }), evidence,
      f.suggested_fix ? el("h4", { text: "Suggested fix" }) : null,
      f.suggested_fix ? richText("p", f.suggested_fix, { class: "fix" }) : null,
    );
    const details = el("details", i === 0 ? { open: "" } : {}, summary, body);
    return el("li", { class: "finding", "data-sev": f.severity }, details);
  }));
}

function renderDropped(dropped) {
  const list = $("#dropped");
  if (!dropped.length) {
    list.replaceChildren(el("li", { text: "Nothing was filtered." }));
    return;
  }
  list.replaceChildren(...dropped.map((d) => el("li", {},
    richText("span", d.finding.title, { class: "d-title" }),
    el("span", { class: "d-loc", text: `${d.finding.file_path}:${d.finding.line}` }),
    richText("span", d.reason, { class: "d-reason" }),
  )));
}

function renderTimings(report) {
  const t = report.timings_ms;
  const total = Math.max(report.total_latency_ms, 1);
  const analyze = t.analyze_impact || 0;
  const agentMax = Math.max(0, ...AGENT_NODES.map((n) => t[n] || 0));
  const spans = [
    ["analyze_impact", 0, analyze, ""],
    ...AGENT_NODES.map((n) => [n, analyze, t[n] || 0, "agent"]),
    ["critic_synthesizer", analyze + agentMax, t.critic_synthesizer || 0, ""],
  ];
  const rows = spans.map(([name, start, ms, cls]) => {
    const bar = el("span", { class: "t-bar" });
    bar.style.left = `${(start / total) * 100}%`;
    bar.style.width = `${Math.max((ms / total) * 100, 0.6)}%`;
    return el("div", { class: `t-row ${cls}` },
      el("span", { class: "t-name", text: name }),
      el("span", { class: "t-track" }, bar),
      el("span", { class: "t-ms", text: `${ms.toFixed(ms < 10 ? 1 : 0)} ms` }),
    );
  });
  rows.push(el("div", { class: "t-row t-total" },
    el("span", { class: "t-name", text: "end to end" }), el("span"),
    el("span", { class: "t-ms", text: `${Math.round(total)} ms` })));
  $("#timings").replaceChildren(...rows);
}

function downloadReport() {
  if (!lastReport) return;
  const blob = new Blob([JSON.stringify(lastReport, null, 2)], { type: "application/json" });
  const link = el("a", { href: URL.createObjectURL(blob), download: "aegispr-report.json" });
  document.body.append(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(link.href);
}

async function loadStaticDemo() {
  try {
    const [report, diff] = await Promise.all([
      fetch("static/demo/sample-report.json").then((r) => (r.ok ? r.json() : Promise.reject())),
      fetch("static/demo/sample.diff").then((r) => (r.ok ? r.text() : Promise.reject())),
    ]);
    return { report, sample: { repo_path: "sample_repo", diff } };
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------- boot

async function boot() {
  const status = $("#status");
  try {
    const [health, repos] = await Promise.all([api("health"), api("repos")]);
    status.dataset.state = "ok";
    $("#status-text").textContent = health.mode === "live" ? "Live model connected" : "Offline mode, no API key needed";
    $("#repo").replaceChildren(...repos.map((r) => el("option", { value: r, text: r })));
  } catch (err) {
    staticDemo = await loadStaticDemo();
    if (staticDemo) {
      status.dataset.state = "ok";
      $("#status-text").textContent = "Hosted preview, sample PR only";
      $("#repo").replaceChildren(el("option", { value: staticDemo.sample.repo_path, text: staticDemo.sample.repo_path }));
      $("#demo-note").hidden = false;
    } else {
      status.dataset.state = "error";
      $("#status-text").textContent = "API unreachable";
      showError(`Can't reach the AegisPR API: ${err.message}. Start it with uv run aegispr serve.`);
    }
  }

  $("#review-form").addEventListener("submit", runReview);
  $("#load-sample").addEventListener("click", () => loadSample().catch((e) => showError(e.message)));
  $("#diff").addEventListener("input", (e) => $("#diff-meta").textContent = describeDiff(e.target.value));
  $("#diff-file").addEventListener("change", async (e) => {
    const file = e.target.files[0];
    if (file) setDiff(await file.text());
  });
  $("#download").addEventListener("click", downloadReport);

  // `/?demo=1` loads and reviews the sample PR immediately (used for screenshots and demos).
  if (staticDemo || new URLSearchParams(location.search).has("demo")) {
    await loadSample();
    await runReview();
  }
}

boot();
